// /install.sh installs the newest agent release from GitHub (deb or rpm for dnf and zypper,
// checksum verified, osquery repository with pinned key) and enrolls the
// device. It contains no secret: the token comes from LIMDM_TOKEN or from an
// existing /etc/limdm/enroll.conf, so the same script serves mass deployment.

var repoNameRe = regexp.MustCompile(`^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$`)

var installTmpl = template.Must(template.New("install").Delims("[[", "]]").Parse(`#!/bin/sh
# LiMDM agent installer, generated by [[.Console]]
#
#   curl -fsSL [[.Console]]/install.sh | sudo LIMDM_TOKEN=<token> sh
#
# Installs the newest limdm-agent release from https://github.com/[[.Repo]]
# (deb or rpm, SHA-256 verified) with osquery, writes /etc/limdm/enroll.conf
# and enrolls the device. Without LIMDM_TOKEN an existing
# /etc/limdm/enroll.conf is used (mass deployment).
set -eu

SERVER='[[.Server]]'
FINGERPRINT='[[.Fingerprint]]'
REPO='[[.Repo]]'

[ "$(id -u)" -eq 0 ] || { echo "run as root" >&2; exit 1; }
for c in curl sha256sum; do command -v "$c" >/dev/null 2>&1 || { echo "$c is required" >&2; exit 1; }; done

case "$(uname -m)" in
    x86_64|amd64) arch=amd64 ;;
    aarch64|arm64) arch=arm64 ;;
    *) echo "unsupported architecture $(uname -m)" >&2; exit 1 ;;
esac
if command -v apt-get >/dev/null 2>&1; then ext=deb
elif command -v dnf >/dev/null 2>&1; then ext=rpm
elif command -v zypper >/dev/null 2>&1; then ext=rpm # openSUSE, SLES
elif command -v pacman >/dev/null 2>&1; then ext=pkg.tar.zst
elif command -v apk >/dev/null 2>&1; then ext=apk
else echo "needs apt-get, dnf, zypper, pacman or apk; other systems: install the tar.gz release manually" >&2; exit 1
fi

install -d -m 0700 /etc/limdm
allow=false
[ "${LIMDM_ALLOW_SCRIPTS:-}" = true ] && allow=true
shell=false
[ "${LIMDM_ALLOW_REMOTE_SHELL:-}" = true ] && shell=true
if [ -n "${LIMDM_TOKEN:-}" ]; then
    case "$LIMDM_TOKEN" in *[!A-Za-z0-9_-]*) echo "invalid token" >&2; exit 1 ;; esac
    umask 077
    cat > /etc/limdm/enroll.conf <<CONF
server = "$SERVER"
fingerprint = "$FINGERPRINT"
token = "$LIMDM_TOKEN"
allow_scripts = $allow
allow_remote_shell = $shell
CONF
elif [ ! -f /etc/limdm/enroll.conf ] && [ ! -f /etc/limdm/device.pem ]; then
    echo "set LIMDM_TOKEN or place /etc/limdm/enroll.conf" >&2; exit 1
fi

tag=$(curl -fsSL "https://api.github.com/repos/$REPO/releases/latest" | sed -n 's/.*"tag_name": *"\([^"]*\)".*/\1/p' | head -n1)
case "$tag" in v[0-9]*) ;; *) echo "no release found in $REPO" >&2; exit 1 ;; esac
ver=${tag#v}
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
pkg="limdm-agent_${ver}_linux_${arch}.${ext}"
base="https://github.com/$REPO/releases/download/$tag"
curl -fsSL -o "$tmp/$pkg" "$base/$pkg"
curl -fsSL -o "$tmp/sums" "$base/limdm_${ver}_SHA256SUMS"
( cd "$tmp" && grep " $pkg\$" sums | sha256sum -c - ) || { echo "checksum mismatch for $pkg" >&2; exit 1; }

key=$(cat <<'KEY'
[[.OsqueryKey]]
KEY
)
if [ "$ext" = pkg.tar.zst ]; then
    pacman -U --noconfirm "$tmp/$pkg" # osquery is not packaged for Arch: native inventory
elif [ "$ext" = apk ]; then
    # apk does not know the release key; the SHA-256 was checked against the release sums above
    apk add --allow-untrusted --no-interactive "$tmp/$pkg"
elif [ "$ext" = deb ]; then
    install -d -m 0755 /etc/apt/keyrings
    printf '%s\n' "$key" > /etc/apt/keyrings/limdm-osquery.asc
    chmod 0644 /etc/apt/keyrings/limdm-osquery.asc
    cat > /etc/apt/sources.list.d/limdm-osquery.sources <<'SRC'
# Managed by LiMDM. Local changes are overwritten.
Types: deb
URIs: https://pkg.osquerypackages.com/deb
Suites: deb
Components: main
Architectures: amd64 arm64
Signed-By: /etc/apt/keyrings/limdm-osquery.asc
SRC
    apt-get update -qq
    DEBIAN_FRONTEND=noninteractive apt-get install -y -q -o Dpkg::Options::=--force-confold osquery "$tmp/$pkg"
elif command -v zypper >/dev/null 2>&1 && ! command -v dnf >/dev/null 2>&1; then
    # SUSE: rpm trusts the key first, so zypper does not ask; the agent rpm is
    # unsigned, its SHA-256 was checked against the release sums above
    install -d -m 0755 /etc/pki/rpm-gpg
    printf '%s\n' "$key" > /etc/pki/rpm-gpg/RPM-GPG-KEY-limdm-osquery
    rpm --import /etc/pki/rpm-gpg/RPM-GPG-KEY-limdm-osquery
    cat > /etc/zypp/repos.d/limdm-osquery.repo <<'REPO'
# Managed by LiMDM. Local changes are overwritten.
[limdm-osquery]
name=osquery
baseurl=https://pkg.osquerypackages.com/rpm/$basearch/
enabled=1
autorefresh=1
type=rpm-md
gpgcheck=1
gpgkey=file:///etc/pki/rpm-gpg/RPM-GPG-KEY-limdm-osquery
REPO
    zypper --non-interactive install --allow-unsigned-rpm osquery "$tmp/$pkg"
else
    install -d -m 0755 /etc/pki/rpm-gpg
    printf '%s\n' "$key" > /etc/pki/rpm-gpg/RPM-GPG-KEY-limdm-osquery
    cat > /etc/yum.repos.d/limdm-osquery.repo <<'REPO'
# Managed by LiMDM. Local changes are overwritten.
[limdm-osquery]
name=osquery
baseurl=https://pkg.osquerypackages.com/rpm/$basearch/
enabled=1
gpgcheck=1
gpgkey=file:///etc/pki/rpm-gpg/RPM-GPG-KEY-limdm-osquery
REPO
    dnf install -y -q osquery "$tmp/$pkg"
fi
if [ -d /run/systemd/system ]; then
    systemctl enable --now limdm-agent.service
else
    rc-update add limdm-agent default && rc-service limdm-agent start
fi
echo "limdm-agent $ver installed"
`))

func (s *Server) installScript(w http.ResponseWriter, r *http.Request) {
	repo := s.cfg.ReleaseRepo
	if !repoNameRe.MatchString(repo) || strings.ContainsAny(s.cfg.AgentURL+s.cfg.PublicURL, "'\"`$\\\n ") {
		http.Error(w, "release repository not configured", http.StatusNotFound)
		return
	}
	var b strings.Builder
	err := installTmpl.Execute(&b, map[string]string{"Console": s.cfg.PublicURL, "Server": s.cfg.AgentURL,
		"Fingerprint": s.tlsCA().Fingerprint(), "Repo": repo, "OsqueryKey": strings.TrimSpace(api.OsqueryKey)})
	if err != nil {
		s.fail(w, err)
		return
	}
	w.Header().Set("Content-Type", "text/x-shellscript; charset=utf-8")
	w.Header().Set("Cache-Control", "no-cache")
	w.Write([]byte(b.String()))
}
