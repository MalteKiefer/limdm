package server

import "testing"

type verCase struct {
	a, b string
	want int
}

func checkCompare(t *testing.T, name string, cmp func(a, b string) int, cases []verCase) {
	t.Helper()
	for _, c := range cases {
		if got := cmp(c.a, c.b); got != c.want {
			t.Errorf("%s: %s vs %s = %d, want %d", name, c.a, c.b, got, c.want)
		}
		if got := cmp(c.b, c.a); got != -c.want {
			t.Errorf("%s: %s vs %s (reversed) = %d, want %d", name, c.b, c.a, got, -c.want)
		}
	}
}

